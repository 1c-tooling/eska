//! Native UUID policy and accepted class guard new inline composition in either source envelope.

use std::fs;

use eska::project_core::{
    MetadataKind,
    source_format::{
        AcceptedBase, Child, Descriptor, MetadataNode, ObjectSource, Operation, PermissionReason,
        Property, PropertyName, PropertyValue, Section, accept_source, import_designer,
        import_designer_readable, prepare_protected,
    },
};

use super::baseline::{tree, uuid};
use crate::support::TestDir;

/// Keep the existing supplier-policy UUID while changing only the owned fixture's declared class.
pub(super) fn locked_enum_fixture(root: &std::path::Path) -> std::path::PathBuf {
    let input = super::baseline::fixture(root);
    let configuration = input.join("Configuration.xml");
    let text = fs::read_to_string(&configuration)
        .unwrap()
        .replace("<Catalog>Sample</Catalog>", "<Enum>Sample</Enum>");
    fs::write(configuration, text).unwrap();
    fs::rename(input.join("Catalogs"), input.join("Enums")).unwrap();
    let file = input.join("Enums/Sample.xml");
    let mut descriptor = Descriptor::from_xml(&fs::read_to_string(&file).unwrap()).unwrap();
    set_class(&mut descriptor.object, MetadataKind::Enum);
    for section in &mut descriptor.object.sections {
        if let Section::Children(children) = section {
            children.retain(|child| !matches!(child, Child::Inline { object } if object.kind == MetadataKind::TabularSection));
            for child in children {
                if let Child::Inline { object } = child {
                    set_class(object, MetadataKind::EnumValue);
                }
            }
        }
    }
    fs::write(file, descriptor.to_xml().unwrap()).unwrap();
    input
}

/// A synthetic class change retains the common properties while removing former owner-specific domains.
fn set_class(object: &mut MetadataNode, kind: MetadataKind) {
    object.kind = kind;
    for section in &mut object.sections {
        if let Section::Properties(properties) = section {
            properties.retain(|property| {
                matches!(
                    property,
                    Property::Typed {
                        name: PropertyName::Name | PropertyName::Synonym | PropertyName::Comment,
                        ..
                    }
                )
            });
        }
    }
}

/// The new value has no opaque or generated bytes and cannot grant itself native supplier permission.
pub(super) fn addition() -> Child {
    Child::Inline {
        object: Box::new(MetadataNode {
            kind: MetadataKind::EnumValue,
            uuid: uuid('9'),
            namespaces: Vec::new(),
            attributes: Vec::new(),
            sections: vec![Section::Properties(vec![
                Property::Typed {
                    name: PropertyName::Name,
                    value: PropertyValue::Text("NewValue".into()),
                },
                Property::Typed {
                    name: PropertyName::Synonym,
                    value: PropertyValue::Empty,
                },
                Property::Typed {
                    name: PropertyName::Comment,
                    value: PropertyValue::Empty,
                },
            ])],
        }),
    }
}

/// A supplier-locked parent refuses additions while its explicitly editable child's property survives.
#[test]
fn locked_native_enum_cannot_create_values_or_mask_allowed_child_property_edits() {
    for readable in [false, true] {
        let test = TestDir::new();
        let input = locked_enum_fixture(&test.0);
        let source = test.0.join("source");
        if readable {
            import_designer_readable(&input, &source).unwrap();
        } else {
            import_designer(&input, &source).unwrap();
        }
        let base_root = test.0.join("accepted");
        let pin = accept_source(&source, &base_root, &[]).unwrap();
        let base = AcceptedBase::open(&base_root, &pin).unwrap();
        assert_eq!(
            base.permission(&uuid('2'), Operation::Create).reason,
            PermissionReason::NativeRestriction
        );
        let path = source.join("Enums/Sample/object.yaml");
        let mut owner = ObjectSource::from_yaml(&fs::read_to_string(&path).unwrap()).unwrap();
        for section in &mut owner.document.descriptor.object.sections {
            if let Section::Children(children) = section {
                let Child::Inline { object } = &mut children[0] else {
                    unreachable!()
                };
                for section in &mut object.sections {
                    if let Section::Properties(properties) = section {
                        for property in properties {
                            if let Property::Typed {
                                name: PropertyName::Comment,
                                value,
                            } = property
                            {
                                *value = PropertyValue::Text("Allowed child edit".into());
                            }
                        }
                    }
                }
                children.insert(1, addition());
            }
        }
        fs::write(path, owner.to_yaml().unwrap()).unwrap();
        let authored = tree(&source);
        let accepted = tree(&base_root);
        let output = test.0.join("generations");
        let failure = prepare_protected(&source, &base, &output, true).unwrap_err();
        assert_eq!(failure.diagnostics.len(), 1);
        assert_eq!(failure.diagnostics[0].operation, Operation::Create);
        assert_eq!(failure.diagnostics[0].uuid, Some(uuid('2')));
        assert_eq!(
            failure.diagnostics[0].reason,
            PermissionReason::NativeRestriction
        );
        assert!(!output.exists());
        let restored = prepare_protected(&source, &base, &output, false).unwrap();
        let native = fs::read_to_string(restored.xml().join("Enums/Sample.xml")).unwrap();
        assert!(!native.contains("NewValue"));
        assert!(native.contains("Allowed child edit"));
        assert_eq!(tree(&source), authored);
        assert_eq!(tree(&base_root), accepted);
    }
}

/// Working class edits cannot upgrade an unrestricted catalog into an accepted creation profile.
#[test]
fn unsupported_accepted_owner_refuses_new_values_even_with_a_working_enum_class() {
    let test = TestDir::new();
    let input = super::fixture(&test.0);
    fs::remove_file(input.join("Ext/ParentConfigurations.bin")).unwrap();
    let source = test.0.join("source");
    import_designer_readable(&input, &source).unwrap();
    let base_root = test.0.join("accepted");
    let pin = accept_source(&source, &base_root, &[]).unwrap();
    let base = AcceptedBase::open(&base_root, &pin).unwrap();
    assert_eq!(
        base.permission(&uuid('2'), Operation::Create).reason,
        PermissionReason::UnsupportedOperation
    );
    let path = source.join("Catalogs/Sample/object.yaml");
    let mut owner = ObjectSource::from_yaml(&fs::read_to_string(&path).unwrap()).unwrap();
    owner.document.descriptor.object.kind = MetadataKind::Enum;
    for section in &mut owner.document.descriptor.object.sections {
        if let Section::Children(children) = section {
            children.push(addition());
        }
    }
    fs::write(path, serde_json::to_string_pretty(&owner).unwrap()).unwrap();
    let before = tree(&source);
    assert!(prepare_protected(&source, &base, &test.0.join("generations"), true).is_err());
    assert!(!test.0.join("generations").exists());
    let restored = prepare_protected(&source, &base, &test.0.join("generations"), false).unwrap();
    let native = fs::read_to_string(restored.xml().join("Catalogs/Sample.xml")).unwrap();
    assert!(!native.contains("NewValue"));
    assert!(native.contains("<Catalog uuid="));
    assert_eq!(tree(&source), before);
}
