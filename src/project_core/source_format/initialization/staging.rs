//! Candidate producers clean only private output; public ownership starts at exclusive publication.

use std::{collections::BTreeMap, fs, path::PathBuf};

use super::{
    ACCEPTED, AcceptedBase, AcceptedRef, Error, ImportAncestorRef, Inventory,
    PROJECT_SOURCE_IMPORT_DIRECTORY, ProjectInitializationPlan, files,
};
use crate::project_core::source_format::{
    ImportAncestor, SourcePath, accept_source,
    layout::migration::publication::{self as storage, View},
    synchronization::stage_project_import_ancestor,
};

pub(super) struct Stage {
    path: PathBuf,
}

pub(super) struct Candidates {
    pub accepted: AcceptedRef,
    pub ancestor: ImportAncestorRef,
    pub stores: Vec<CandidateStore>,
}

pub(super) struct CandidateStore {
    pub relative: &'static str,
    pub inventory: Inventory,
    pub claimed: bool,
    complete: bool,
    root: PathBuf,
    ready: &'static str,
    text: BTreeMap<SourcePath, String>,
}

impl Stage {
    /// Claim a new private directory within the existing root without touching preexisting entries.
    pub(super) fn claim(plan: &ProjectInitializationPlan) -> Result<Self, Error> {
        plan.recheck()?;
        let mut nonce = [0_u8; 16];
        getrandom::fill(&mut nonce).map_err(|_| Error::root("source_entropy_unavailable"))?;
        let path = plan.root.join(format!(".eska-init-{}", files::hex(&nonce)));
        fs::create_dir(&path).map_err(|error| files::io(&error))?;
        Ok(Self { path })
    }

    /// Both producer references and pre-publication fingerprints must describe the planned source.
    pub(super) fn prepare(&self, plan: &ProjectInitializationPlan) -> Result<Candidates, Error> {
        let mut stores = Vec::new();
        let accepted = if let Some(approved) = &plan.approved {
            approved.clone()
        } else {
            let root = self.path.join("accepted");
            let reference = accept_source(plan.project.source(), &root, &[])?;
            if AcceptedBase::open(&root, &reference)?.package.snapshot != plan.inventory {
                return Err(Error::root("source_input_changed"));
            }
            stores.push(CandidateStore::capture(ACCEPTED, root, "accepted.json")?);
            reference
        };
        let ancestor = if let Some(existing) = &plan.ancestor {
            existing.clone()
        } else {
            let root = self.path.join("source-import");
            let reference = stage_project_import_ancestor(&plan.project, &root)?;
            if ImportAncestor::open(&root.join("initial"), &reference)?.revision()
                != plan.inventory.revision
            {
                return Err(Error::root("source_input_changed"));
            }
            stores.push(CandidateStore::capture(
                PROJECT_SOURCE_IMPORT_DIRECTORY,
                root,
                "state.json",
            )?);
            reference
        };
        plan.recheck()?;
        Ok(Candidates {
            accepted,
            ancestor,
            stores,
        })
    }

    /// Private producer output is cleaned even when publication or its ownership rollback fails.
    pub(super) fn remove(self) -> Result<(), Error> {
        let safe = self
            .path
            .parent()
            .is_some_and(|root| super::check_root(root).is_ok())
            && super::checked_directory(&self.path).is_ok();
        if !safe {
            return Err(Error::root("source_cleanup_failed")
                .in_field(self.path.to_string_lossy().into_owned()));
        }
        fs::remove_dir_all(&self.path).map_err(|_| {
            Error::root("source_cleanup_failed").in_field(self.path.to_string_lossy().into_owned())
        })
    }
}

impl CandidateStore {
    /// Capture generated bytes before any public destination can supply ownership evidence.
    fn capture(relative: &'static str, root: PathBuf, ready: &'static str) -> Result<Self, Error> {
        let inventory = Inventory::read(&root)?;
        Ok(Self {
            relative,
            inventory,
            claimed: false,
            complete: false,
            root,
            ready,
            text: BTreeMap::new(),
        })
    }

    /// Existing storage publication supplies its own receipt and preserves ready-marker ordering.
    pub(super) fn publish(&mut self, plan: &ProjectInitializationPlan) -> Result<(), Error> {
        storage::publish_new(
            Self::view(&self.root, &self.inventory, &self.text, self.ready),
            &plan.root.join(self.relative),
            &mut self.claimed,
        )?;
        self.complete = true;
        Ok(())
    }

    /// Incomplete public stores may contain only exact generated output and its reserved bytes.
    pub(super) fn matches_owned_partial(&self, plan: &ProjectInitializationPlan) -> bool {
        if self.complete {
            return Inventory::read(&plan.root.join(self.relative))
                .is_ok_and(|current| current == self.inventory);
        }
        storage::matches_owned_partial(
            Self::view(&self.root, &self.inventory, &self.text, self.ready),
            &plan.root.join(self.relative),
        )
        .is_ok_and(|matches| matches)
    }

    /// The same immutable stage snapshot binds publication and subsequent cleanup checks.
    const fn view<'a>(
        root: &'a std::path::Path,
        inventory: &'a Inventory,
        text: &'a BTreeMap<SourcePath, String>,
        ready: &'a str,
    ) -> View<'a> {
        View {
            root,
            input: inventory,
            output: inventory,
            text,
            ready,
            renamed: None,
        }
    }
}
